// Concatenates src/*.js (in name order) into code.js, the file Figma runs.
// Usage: node design/redesign-plugin/build.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const src = join(here, 'src')
const parts = readdirSync(src).filter(f => f.endsWith('.js')).sort()
const body = parts.map(f => `// ---- ${f}\n` + readFileSync(join(src, f), 'utf8')).join('\n')
writeFileSync(join(here, 'code.js'), `// GENERATED by build.mjs from src/ — do not edit.\n${body}`)
console.log(`code.js: ${parts.length} parts, ${body.length} chars`)
